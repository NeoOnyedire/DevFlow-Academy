import { beforeEach, describe, expect, it, vi } from 'vitest'
import type { VercelRequest, VercelResponse } from '../api/_lib/vercel'
import { getCurrentWeekKey, getWeeklyChallenge } from '../shared/weeklyChallenge.js'

const mocks = vi.hoisted(() => ({
  sql: vi.fn(),
  getUserIdFromRequest: vi.fn(),
  getUserById: vi.fn(),
}))

vi.mock('../api/_lib/db.js', () => ({ sql: mocks.sql }))
vi.mock('../api/_lib/session.js', () => ({ getUserIdFromRequest: mocks.getUserIdFromRequest }))
vi.mock('../api/_lib/users.js', () => ({ getUserById: mocks.getUserById }))

import handler from '../api/leaderboard.js'

function createResponse() {
  return {
    statusCode: 0,
    body: undefined as unknown,
    status(code: number) {
      this.statusCode = code
      return this
    },
    json(body: unknown) {
      this.body = body
      return this
    },
  }
}

async function postLeaderboard(body: unknown) {
  const req = { method: 'POST', body, query: {} } as unknown as VercelRequest
  const res = createResponse()
  await handler(req, res as unknown as VercelResponse)
  return res
}

async function getLeaderboard(query: Record<string, string | string[]> = {}) {
  const req = { method: 'GET', query } as unknown as VercelRequest
  const res = createResponse()
  await handler(req, res as unknown as VercelResponse)
  return res
}

beforeEach(() => {
  mocks.sql.mockReset().mockResolvedValue({ rows: [] })
  mocks.getUserIdFromRequest.mockReset().mockReturnValue('user-1')
  mocks.getUserById.mockReset().mockResolvedValue({ id: 'user-1', name: 'Ada' })
})

describe('leaderboard challenge submissions', () => {
  it('requires a signed-in user to submit a challenge or read personal history', async () => {
    mocks.getUserIdFromRequest.mockReturnValue(null)

    const postResponse = await postLeaderboard({
      weekKey: getCurrentWeekKey(),
      challengeId: getWeeklyChallenge(getCurrentWeekKey(), 'junior-dev').id,
    })
    const mineResponse = await getLeaderboard({ mine: '1' })

    expect(postResponse.statusCode).toBe(401)
    expect(mineResponse.statusCode).toBe(401)
    expect(mocks.sql).not.toHaveBeenCalled()
  })

  it('rejects challenge IDs that were not generated by the server', async () => {
    const response = await postLeaderboard({
      weekKey: getCurrentWeekKey(),
      challengeId: `${getCurrentWeekKey()}-fake-1000-points`,
      points: 1000,
    })

    expect(response.statusCode).toBe(400)
    expect(mocks.sql).not.toHaveBeenCalled()
  })

  it('rejects challenge submissions for a different week', async () => {
    const response = await postLeaderboard({
      weekKey: '2099-W01',
      challengeId: '2099-W01-junior-dev-branch-rescue',
      points: 1000,
    })

    expect(response.statusCode).toBe(400)
    expect(mocks.sql).not.toHaveBeenCalled()
  })

  it('stores the server-defined reward, ignoring a caller-supplied points value', async () => {
    const weekKey = getCurrentWeekKey()
    const challenge = getWeeklyChallenge(weekKey, 'junior-dev')
    const response = await postLeaderboard({
      weekKey,
      challengeId: challenge.id,
      points: 1000,
    })

    expect(response.statusCode).toBe(200)
    const queryArguments = mocks.sql.mock.calls[0] as unknown as unknown[]
    expect(queryArguments[3]).toBe(challenge.reward)
    expect(queryArguments[3]).not.toBe(1000)
  })

  it('returns a clear error when the leaderboard cannot be loaded', async () => {
    mocks.sql.mockRejectedValueOnce(new Error('database unavailable'))

    const response = await getLeaderboard({ week: getCurrentWeekKey() })

    expect(response.statusCode).toBe(502)
    expect(response.body).toEqual({ error: 'Could not load the leaderboard right now.' })
  })

  it('returns a clear error when challenge points cannot be saved', async () => {
    mocks.sql.mockRejectedValueOnce(new Error('database unavailable'))
    const weekKey = getCurrentWeekKey()
    const challenge = getWeeklyChallenge(weekKey, 'junior-dev')

    const response = await postLeaderboard({ weekKey, challengeId: challenge.id })

    expect(response.statusCode).toBe(502)
    expect(response.body).toEqual({ error: 'Could not save your challenge points right now.' })
  })
})
